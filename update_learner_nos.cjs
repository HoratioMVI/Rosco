const learners = db.prepare('SELECT id, idNumber FROM learners').all();

db.transaction(() => {
  for (const learner of learners) {
    // Match by cleaning ID number (some might have slight diffs due to seeding)
    // We try to find the best match in the mapping
    let matchedLearnerNo = null;
    
    // Exact match
    if (mapping[learner.idNumber]) {
      matchedLearnerNo = mapping[learner.idNumber];
    } else {
      // Fuzzy match (first 10 digits as IDs in image were slightly different in some cases)
      const partialId = learner.idNumber.substring(0, 10);
      for (const [imgId, laNo] of Object.entries(mapping)) {
        if (imgId.startsWith(partialId)) {
          matchedLearnerNo = laNo;
          break;
        }
      }
    }

    if (matchedLearnerNo) {
      db.prepare('UPDATE learners SET learnerNo = ? WHERE id = ?').run(matchedLearnerNo, learner.id);
      
      // Update other tables
      db.prepare('UPDATE daily_attendance SET learnerNo = ? WHERE learnerId = ?').run(matchedLearnerNo, learner.id);
      db.prepare('UPDATE theory_books SET learnerNo = ? WHERE learnerId = ?').run(matchedLearnerNo, learner.id);
    }
  }
})();

